/* 液晶用のドット絵アイコンとインジケーター（192×64 ドット座標） */
(function (C) {
  'use strict';

  // 文字列のドット絵 -> SVG（'#' が点灯ドット）
  function PIX(rows, cls) {
    const h = rows.length, w = Math.max(...rows.map((r) => r.length));
    let rects = '';
    rows.forEach((r, y) => {
      let x = 0;
      while (x < r.length) {
        if (r[x] === '#') { let e = x; while (e < r.length && r[e] === '#') e++; rects += '<rect x="' + x + '" y="' + y + '" width="' + (e - x) + '" height="1"/>'; x = e; } else x++;
      }
    });
    return '<svg ' + (cls ? 'class="' + cls + '" ' : '') + 'width="' + w + '" height="' + h + '" viewBox="0 0 ' + w + ' ' + h + '" fill="currentColor" shape-rendering="crispEdges" aria-hidden="true">' + rects + '</svg>';
  }
  C.PIX = PIX;

  const LET = {
    D: ['##.', '#.#', '#.#', '#.#', '##.'], R: ['##.', '#.#', '##.', '#.#', '#.#'], G: ['.##', '#..', '#.#', '#.#', '.##'], S: ['.##', '#..', '.#.', '..#', '##.'],
  };
  function boxed(l) {
    const g = LET[l];
    return PIX(['#######'].concat(g.map((r) => '#.' + r + '.#'), ['#######']));
  }
  function filledLetter(l) {
    const g = LET[l];
    return PIX(['#######'].concat(g.map((r) => '##' + r.replace(/#/g, 'x').replace(/\./g, '#').replace(/x/g, '.') + '##'), ['#######']));
  }

  C.IC = {
    tri: PIX(['#...', '##..', '###.', '####', '###.', '##..', '#...']),
    triOpen: PIX(['#...', '##..', '#.#.', '#..#', '#.#.', '##..', '#...']),
    radioOff: PIX(['..###..', '.#...#.', '#.....#', '#.....#', '#.....#', '.#...#.', '..###..']),
    radioOn: PIX(['..###..', '.#...#.', '#.###.#', '#.###.#', '#.###.#', '.#...#.', '..###..']),
    play: PIX(['..#####..', '.##.####.', '###..####', '###...###', '###....##', '###...###', '###..####', '.##.####.', '..#####..']),
    minus: PIX(['..#####..', '.#######.', '#########', '#########', '##.....##', '#########', '#########', '.#######.', '..#####..']),
    warn: PIX(['.......#.......', '......###......', '......###......', '.....##.##.....', '.....##.##.....', '....###.###....', '....###.###....', '...####.####...', '...#########...', '..#####.#####..', '..###########..', '.#############.', '###############']),
    check: PIX(['..###..', '.####.#', '####.##', '#.#.###', '##.####', '.#####.', '..###..']),
    up: PIX(['...#...', '..###..', '.#####.', '#######']),
    down: PIX(['#######', '.#####.', '..###..', '...#...']),
    eng: PIX(['#####..', '.#.....', '..#....', '.......', '....#..', '.....#.', '..#####']),
    engR: PIX(['.#...', '##...', '#####', '##...', '.#...', '.....', '...#.', '...##', '#####', '...##', '...#.']),
    lock: PIX(['.###.', '#...#', '#...#', '#####', '##.##', '##.##', '#####']),
    more: PIX(['#..', '##.', '#.#', '##.', '#..']),
    mathInd: PIX(['..........#####.......', '..........#...#....##.', '.......#..#...#...##..', '#......#..#...#..##...', '.#....#...#...#.##....', '..#..#....#####.#.....', '...##...........#.....']),
    sun: PIX(['#..#..#', '.#####.', '.##.##.', '###.###', '.##.##.', '.#####.', '#..#..#']),
    cxI: PIX(['...#', '....', '..##', '..#.', '.##.', '.#..', '###.']),
    cxA: PIX(['....#', '...#.', '..#..', '.#...', '#####']),
    angle: (u) => boxed({ deg: 'D', rad: 'R', gra: 'G' }[u] || 'D'),
    shift: filledLetter('S'),
  };

  // ---- HOME のアプリアイコン（ドット絵） ----
  const T3 = { // 3×5 ドット文字
    '0': ['###', '#.#', '#.#', '#.#', '###'], '1': ['.#.', '##.', '.#.', '.#.', '###'], '2': ['##.', '..#', '.#.', '#..', '###'], '6': ['.##', '#..', '###', '#.#', '###'], '8': ['###', '#.#', '###', '#.#', '###'],
    X: ['#.#', '#.#', '.#.', '#.#', '#.#'], Y: ['#.#', '#.#', '.#.', '.#.', '.#.'], '=': ['...', '###', '...', '###', '...'], '>': ['#..', '.#.', '..#', '.#.', '#..'], ' ': ['...', '...', '...', '...', '...'],
  };
  function text3(s, under) {
    const rows = ['', '', '', '', ''];
    for (const ch of s) { const g = T3[ch] || T3[' ']; for (let i = 0; i < 5; i++) rows[i] += g[i] + '.'; }
    if (under) rows.push('', '#'.repeat(rows[0].length - 1));
    return rows;
  }
  const APPICON = {
    calc: ['#...#....#.....', '.#.#...#####...', '..#...........', '.#.#.....#.....', '#...#..........', '...............', '..#.....#####..', '#####..........', '..#............'].map((r) => r.padEnd(15, '.')),
    stat: ['#.......##.....', '#....##.##.....', '#.##.##.##.##..', '#.##.##.##.##..', '#.##.##.##.##..', '#.##.##.##.##..', '#############..'],
    dist: ['......###......', '.....#...#.....', '....#.....#....', '...#.......#...', '..##.......##..', '.##.........##.', '###############'],
    sheet: ['###############', '#.#...#...#...#', '###############', '#.#...#...#...#', '###############', '#.#...#...#...#', '###############'],
    table: ['###############', '#......#......#', '#.####.#.####.#', '#......#......#', '#.####.#.####.#', '#......#......#', '###############'],
    eq: text3('XY=0', true),
    ineq: text3('XY>0', true),
    cplx: ['##############', '#.....#......#', '#..##.#....#.#', '#.....#...#..#', '#..##.#..#...#', '#..##.#.#....#', '#..##.#.####.#', '#.....#......#', '##############'],
    base: ['.......#.###.#.##', '###.###.#.#.#.#.#', '..#.#.#.#.#.#.#..', '###.###.#.#.#.###', '#...#.#.#.#.#.#.#', '###.###.#.###.###'],
    mat: ['##.........##', '#..##...##..#', '#..##...##..#', '#............#'.slice(0, 13), '#..##...##..#', '#..##...##..#', '##.........##'],
    vec: ['.##.....####', '####.....###', '.##.....#.##', '.##....#...#', '.##...#.....', '.##..#......', '.##.#.......'],
    mbox: ['#######..#####..', '#.....#.#.....#.', '#.#...#.#..#..#.', '#.....#.#.###.#.', '#...#.#.#..#..#.', '#.....#.#.....#.', '#######..#####..'],
  };
  C.appIcon = (id) => PIX(APPICON[id] || APPICON.calc);

  // ---- インジケーター行 ----
  C.statusHtml = function (st) {
    // st: {shift, math, angle, fix, sci, eng, cx:'i'|'∠', verify, up, down, extra}
    const p = (x, html, cls) => '<span class="ind' + (cls ? ' ' + cls : '') + '" style="left:' + x + 'px">' + html + '</span>';
    let h = '';
    if (st.shift) h += p(1, C.IC.shift);
    if (st.math) h += p(24, C.IC.mathInd);
    h += p(47, C.IC.angle(st.angle));
    if (st.fix) h += p(72, 'FIX', 'txt');
    if (st.sci) h += p(72, 'SCI', 'txt');
    if (st.eng) h += p(92, 'E', 'txt');
    if (st.cx) h += p(103, st.cx === 'i' ? C.IC.cxI : C.IC.cxA);
    if (st.verify) h += p(127, C.IC.check);
    if (st.down) h += p(142, C.IC.down);
    if (st.up) h += p(151, C.IC.up);
    if (st.extra) h += p(160, st.extra, 'txt');
    return h;
  };
})(window.C = window.C || {});
